"""Generate docs/DATA_DICTIONARY.md from the output schema, the mapping and the manifest.

    python -m ahah_ingest.dictionary
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from .columns import MAPPING, SCHEMA, VERSIONS
from .core.output import load_schema
from .core.sources import ROOT, load_registry
from .reader import load_mapping

OUT = ROOT / "docs" / "DATA_DICTIONARY.md"

UNITS = {
    "1": "Accessibility indicators are network distances in kilometres. Passive green space is an area measure of green space within a 900-metre buffer, unit not stated by the paper (Daras et al. 2019); the Scottish values run 0 to 277.5, so it is not a share. Air: annual mean concentrations. The environment domain includes green space as well as the air pollutants.",
    "2": "Units unconfirmed: the version 2 documentation is not held. The column names suggest the revised method. Eleven routed indicators and their deciles hold -1 in S01010206 and S01010226, the likely code for no route; exclude it before averaging. `ur` is a 0/1 flag the build code does not use, probably urban = 1, undocumented.",
    "3": "Accessibility: drive time in minutes. Passive green space: median NDVI. Air: annual mean µg/m³ (v5 methodology, sections 3 and 5). Values may be written in scientific notation in the file; they are stored exactly.",
    "4": "As version 3; values are published to 4 decimals. The five health indicator ranks are dense (ties share a rank and the next rank follows), so the largest health rank is below the number of areas. Zone S01008132 has an air quality domain score of exactly -1.0000, an ordinary value.",
    "5.1": "As version 3, with a 15th indicator, active green space, and a hospital defined as one with an accident and emergency department. Values carry up to 20 fractional digits.",
}


def render() -> str:
    schema = load_schema(SCHEMA)
    mapping = load_mapping(MAPPING)
    registry = load_registry()
    manifest_path = ROOT / "results" / "manifest.json"
    manifest = json.loads(manifest_path.read_text()) if manifest_path.is_file() else None
    reverse = {v: {} for v in VERSIONS}
    for version, m in mapping.items():
        for file_col, table_col in m.items():
            reverse[version][table_col] = file_col
    lines = [f"# Data dictionary: `{schema['table']}`, schema `{schema['version']}`", "",
             "One row per Scottish data zone per AHAH edition. Key: `ahah_version`, `datazone_code`. Column names are",
             "those of the version 5.1 file; earlier editions map onto them (the \"File column\" columns below).",
             "A column an edition does not publish is NULL for it. Generated by `python -m ahah_ingest.dictionary`; do not edit by hand.", ""]
    if manifest:
        lines += [f"Current build: {manifest['csv']['rows']:,} rows by {manifest['csv']['columns']} columns, built {manifest['built_at'][:19]}Z.",
                  f"CSV SHA256 `{manifest['csv']['sha256']}`, Parquet SHA256 `{manifest['parquet']['sha256']}`.", ""]
    lines += ["## Conventions", "", f"- {registry.licence}.",
              "- Every rank, percentile and decile reads 1 as the healthiest area. This is the opposite of SIMD, where 1 is the most deprived.",
              "- Ranks are over Great Britain: 41,729 areas in editions 1 to 3, 42,648 in 4, 43,064 in 5.1. A rank is read with its edition.",
              "- Indicator percentiles run 0 to 100 (101 values), domain and index percentiles 1 to 100. See `PERCENTILES.md`.",
              "- Editions are not comparable with each other: methods, units and geography change. Use one edition per study.",
              "- Editions 1 to 4 are on the 2011 data zones (6,976), edition 5.1 on the 2022 data zones (7,392). The vintages do not nest.",
              "- Scores and indicators are `decimal(38,20)`, stored exactly as published, never through a float.", "",
              "## Units and definitions by edition", ""]
    for v in VERSIONS:
        lines.append(f"- **Version {v}** ({registry.edition(v)['year']}): {UNITS[v]}")
    lines += ["", "## Columns", "", "| Column | SQL type | Null | Editions | Description | File column v1 | v2 | v3 | v4 | v5.1 |", "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    sql = {"string": "nvarchar(16)", "int8": "tinyint", "int16": "smallint", "int32": "int", "decimal": "decimal(38,20)"}
    for f in schema["fields"]:
        cells = [f"`{reverse[v].get(f['name'], '')}`" if reverse[v].get(f["name"]) else "" for v in VERSIONS]
        lines.append(f"| `{f['name']}` | {sql[f['type']]} | {'yes' if f['nullable'] else 'no'} | {', '.join(f['editions'])} | {f['description']} | " + " | ".join(cells) + " |")
    lines += ["", "## Sources", "", "| Edition | File | SHA256 | GB rows | Vintage |", "| --- | --- | --- | --- | --- |"]
    for e in registry.editions:
        lines.append(f"| {e['version']} | `{e['file']}` | `{e['sha256']}` | {e['gb_rows']:,} | {e['vintage']} |")
    lines += ["", "Reference lists of data zones:", ""]
    for vintage, spec in registry.datazone_lists.items():
        lines.append(f"- {vintage}: `{spec['file']}`, {spec['zones']:,} zones, SHA256 `{spec['sha256']}`, from {spec['page']}")
    lines += ["", "## Attribution", ""] + [f"- {a}" for a in registry.attribution] + [""]
    return "\n".join(lines)


def main(argv=None) -> int:
    OUT.write_text(render())
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
